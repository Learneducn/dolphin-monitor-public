import assert from "node:assert/strict";
import worker from "../dist/server/index.js";
let stored=null;
const env={COLLECTOR_TOKEN:"test-secret",BUCKET:{async get(){return stored?{json:async()=>JSON.parse(stored)}:null},async put(_key,value){stored=value}}};
const call=(path,init)=>worker.fetch(new Request(`https://example.test${path}`,init),env,{});
assert.equal((await call("/")).status,200);
assert.equal((await call("/api/snapshot")).status,200);
assert.equal((await call("/api/ingest",{method:"POST",body:"{}",headers:{"content-type":"application/json"}})).status,401);
const payload={version:1,experiments:[],gpus:[],counts:{},generated_at:new Date().toISOString()};
const saved=await call("/api/ingest",{method:"POST",body:JSON.stringify(payload),headers:{"content-type":"application/json","authorization":"Bearer test-secret"}});
assert.equal(saved.status,200);
env.TENSORBOARD_COLLECTOR_TOKEN="tensorboard-secret";
const secondary=await call("/api/ingest",{method:"POST",body:JSON.stringify(payload),headers:{"content-type":"application/json","authorization":"Bearer tensorboard-secret"}});
assert.equal(secondary.status,200);
const legacyAfterTensorBoard=await call("/api/ingest",{method:"POST",body:JSON.stringify({...payload,node_name:"legacy overwrite"}),headers:{"content-type":"application/json","authorization":"Bearer test-secret"}});
assert.equal((await legacyAfterTensorBoard.json()).ignored,true);
const current=await (await call("/api/snapshot")).json();
assert.ok(current.received_at);
assert.equal(current.collector_channel,"tensorboard");
assert.notEqual(current.node_name,"legacy overwrite");
console.log("Worker routes, authorization, and snapshot storage passed");
